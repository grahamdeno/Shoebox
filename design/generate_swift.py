#!/usr/bin/env python3
"""Writes App/Generated/DesignTokens.swift from tokens.json. Run after any token change; CI checks it is current."""
import json, re, sys, pathlib

root = pathlib.Path(__file__).resolve().parent
t = json.loads((root / "tokens.json").read_text())
out = root.parent / "Shared" / "Generated" / "DesignTokens.swift"

def camel(name):
    p = re.split(r"[-\s]+", name)
    return p[0] + "".join(x[:1].upper() + x[1:] for x in p[1:])

def resolve(v, theme, seen=()):
    m = re.fullmatch(r"\{([^}]+)\}", v.strip())
    if not m: return v
    name = m.group(1)
    if name in seen: raise SystemExit(f"Token loop at {name}")
    tok = next(r for r in t["color"]["tokens"] if r["name"] == name)
    val = tok["value"][theme] if isinstance(tok["value"], dict) else tok["value"]
    return resolve(val, theme, seen + (name,))

def rgba(v):
    v = v.strip()
    m = re.fullmatch(r"#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?", v)
    if m:
        h = m.group(1); a = int(m.group(2), 16) / 255 if m.group(2) else 1.0
        return tuple(int(h[i:i+2], 16) / 255 for i in (0, 2, 4)) + (a,)
    m = re.fullmatch(r"rgba?\(([^)]*)\)", v)
    if m:
        parts = [float(x) for x in m.group(1).split(",")]
        return (parts[0]/255, parts[1]/255, parts[2]/255, parts[3] if len(parts) > 3 else 1.0)
    raise SystemExit(f"Can't read color {v!r}")

def px(v): return float(str(v).replace("px", ""))

def f(x): return f"{x:.4f}".rstrip("0").rstrip(".") if "." in f"{x:.4f}" else str(x)

L = ["// Generated by design/generate_swift.py from design/tokens.json. Don't edit by hand.", "",
     "import SwiftUI", "import UIKit", "",
     "/// The two palettes. Each has a day and a night appearance that follows the system setting.",
     "enum Palette: String, CaseIterable, Sendable { case plum, gold }", "",
     "/// Color roles. Use the role, never a raw value.",
     "struct ColorRoles: Sendable {"]
roles = t["color"]["tokens"]
for r in roles:
    L.append(f"    /// {r.get('usage', '').strip()}")
    L.append(f"    let {camel(r['name'])}: Color")
L.append("}")
L.append("")
L.append("extension ColorRoles {")
L.append("    static func dynamic(_ day: (Double, Double, Double, Double), _ night: (Double, Double, Double, Double)) -> Color {")
L.append("        Color(UIColor { $0.userInterfaceStyle == .dark")
L.append("            ? UIColor(red: night.0, green: night.1, blue: night.2, alpha: night.3)")
L.append("            : UIColor(red: day.0, green: day.1, blue: day.2, alpha: day.3) })")
L.append("    }")
L.append("")
L.append("    static func roles(for palette: Palette) -> ColorRoles {")
L.append("        switch palette {")
for pal, day, night in (("plum", "plum-day", "plum-night"), ("gold", "gold-day", "gold-night")):
    L.append(f"        case .{pal}:")
    L.append("            return ColorRoles(")
    args = []
    for r in roles:
        d = ", ".join(f(x) for x in rgba(resolve(r["value"][day], day))); n = ", ".join(f(x) for x in rgba(resolve(r["value"][night], night)))
        args.append(f"                {camel(r['name'])}: dynamic(({d}), ({n}))")
    L.append(",\n".join(args) + ")")
L.append("        }")
L.append("    }")
L.append("}")
L.append("")

fam = {"serif": "DMSerifDisplay-Regular", "sans": "Archivo"}
L.append("/// Type styles. Reasons are DM Serif Display; labels are Archivo. All scale with Dynamic Type.")
L.append("enum TypeStyle: String, CaseIterable, Sendable {")
styles = [(s, g["family"]) for g in t["type"]["groups"] for s in g["styles"]]
for s, _ in styles: L.append(f"    case {camel(s['name'])}")
L.append("")
L.append("    var size: CGFloat { switch self {")
for s, _ in styles: L.append(f"        case .{camel(s['name'])}: {f(px(s['fontSize']))}")
L.append("    } }")
L.append("    var lineHeight: CGFloat { switch self {")
for s, _ in styles: L.append(f"        case .{camel(s['name'])}: {f(px(s['lineHeight']))}")
L.append("    } }")
L.append("    var weight: Font.Weight { switch self {")
wmap = {400: ".regular", 500: ".medium", 600: ".semibold", 700: ".bold"}
for s, _ in styles: L.append(f"        case .{camel(s['name'])}: {wmap[int(s['fontWeight'])]}")
L.append("    } }")
L.append("    var isSerif: Bool { switch self {")
for s, fm in styles: L.append(f"        case .{camel(s['name'])}: {'true' if fm == 'serif' else 'false'}")
L.append("    } }")
L.append("    var uppercase: Bool { self == .meta }")
L.append("    /// The font family's PostScript name as bundled in App/Fonts.")
L.append(f"    var family: String {{ isSerif ? \"{fam['serif']}\" : \"{fam['sans']}\" }}")
L.append("    var relativeTo: Font.TextStyle { switch self {")
rel = {"reasonXl": ".largeTitle", "reasonLg": ".title", "reasonMd": ".title2", "reasonSm": ".title3", "dayNumeral": ".title2",
       "title": ".headline", "body": ".body", "button": ".body", "label": ".footnote", "meta": ".caption2"}
for s, _ in styles: L.append(f"        case .{camel(s['name'])}: {rel.get(camel(s['name']), '.body')}")
L.append("    } }")
L.append("}")
L.append("")

L.append("/// Spacing, corners and sizes in points.")
L.append("enum Metric {")
for grp in ("spacing", "radius", "size"):
    for tok in t[grp]["tokens"]:
        L.append(f"    /// {tok.get('usage', '').strip()}")
        L.append(f"    static let {camel(tok['name'])}: CGFloat = {f(px(tok['value']))}")
L.append("}")
L.append("")
text = "\n".join(L)
if "--check" in sys.argv:
    if not out.exists() or out.read_text() != text:
        sys.exit("DesignTokens.swift is out of date. Run python3 design/generate_swift.py")
    print("DesignTokens.swift is current"); sys.exit(0)
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(text)
print(f"wrote {out}")
